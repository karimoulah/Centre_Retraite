import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

import type { Env } from '../../config/config.module';
import { StorageService } from './storage.service';

type Grant = { op: 'put' | 'get'; key: string; exp: number; type?: string; name?: string };

/**
 * Development and tests: files under STORAGE_LOCAL_DIR, URLs signed with HMAC and served by
 * StorageController, so the frontend follows exactly the same flow as with R2.
 */
export class LocalStorageService extends StorageService {
  private readonly root: string;
  private readonly secret: string;
  private readonly base: string;

  constructor(env: Env) {
    super();
    this.root = resolve(env.STORAGE_LOCAL_DIR);
    this.secret = env.STORAGE_SIGNING_SECRET ?? randomBytes(32).toString('hex');
    this.base = env.STORAGE_PUBLIC_URL.replace(/\/$/, '');
  }

  async signUpload(key: string, contentType: string, expiresIn: number) {
    return `${this.base}/storage/${this.sign({ op: 'put', key, type: contentType, exp: Date.now() + expiresIn * 1000 })}`;
  }

  async signDownload(key: string, fileName: string, expiresIn: number) {
    return `${this.base}/storage/${this.sign({ op: 'get', key, name: fileName, exp: Date.now() + expiresIn * 1000 })}`;
  }

  async stat(key: string) {
    try {
      const info = await stat(this.path(key));
      const meta = await readFile(`${this.path(key)}.type`, 'utf8').catch(() => null);
      return { size: info.size, contentType: meta };
    } catch {
      return null;
    }
  }

  async remove(key: string) {
    await rm(this.path(key), { force: true });
    await rm(`${this.path(key)}.type`, { force: true });
  }

  /** Used by StorageController only. */
  verify(token: string): Grant | null {
    const [payload, signature] = token.split('.');
    if (!payload || !signature) return null;
    const expected = createHmac('sha256', this.secret).update(payload).digest();
    const given = Buffer.from(signature, 'base64url');
    if (given.length !== expected.length || !timingSafeEqual(given, expected)) return null;
    const grant = JSON.parse(Buffer.from(payload, 'base64url').toString()) as Grant;
    return grant.exp > Date.now() ? grant : null;
  }

  async write(key: string, body: Buffer, contentType: string) {
    await mkdir(dirname(this.path(key)), { recursive: true });
    await writeFile(this.path(key), body);
    await writeFile(`${this.path(key)}.type`, contentType);
  }

  read(key: string) {
    return readFile(this.path(key));
  }

  private sign(grant: Grant) {
    const payload = Buffer.from(JSON.stringify(grant)).toString('base64url');
    return `${payload}.${createHmac('sha256', this.secret).update(payload).digest('base64url')}`;
  }

  /** Keys are generated by the API (no "..") but stay inside the root whatever happens. */
  private path(key: string) {
    const full = resolve(join(this.root, key));
    if (!full.startsWith(this.root)) throw new Error('invalid storage key');
    return full;
  }
}
